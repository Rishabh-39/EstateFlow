import assert from 'node:assert/strict';
import { RequestLimiter, RATE_POLICIES, publicWriteRoute, isPrivateResponsePath } from '../src/shared/request-security';
let checks=0;
const ok=(condition:unknown,label:string)=>{ assert.ok(condition,label); checks++; };
ok(publicWriteRoute('POST','/auth/login')==='LOGIN','login write classified');
ok(publicWriteRoute('POST','/auth/login?source=web')==='LOGIN','query string ignored');
ok(publicWriteRoute('POST','/auth/register/')==='REGISTER','trailing slash normalized');
ok(publicWriteRoute('POST','/enquiries')==='ENQUIRY','public enquiry classified');
ok(publicWriteRoute('GET','/auth/login')===null,'GET not limited by write policy');
ok(publicWriteRoute('POST','/staff/enquiries/mock-inbound')===null,'staff endpoint not mistakenly public route');
ok(publicWriteRoute('POST','/auth/login-extra')===null,'prefix does not match');
ok(isPrivateResponsePath('/staff/events') && isPrivateResponsePath('/booking-holds/abc'),'private cache disabled');
ok(!isPrivateResponsePath('/room-types') && !isPrivateResponsePath('/staffing'),'public reads not misclassified');
const limit=new RequestLimiter(2);
const p={limit:2,windowMs:1000};
ok(limit.take('login:1',p,1000).remaining===1,'first request allowed');
ok(limit.take('login:1',p,1001).remaining===0,'second request allowed');
const denied=limit.take('login:1',p,1002);
ok(!denied.allowed && denied.retryAfterSeconds===1,'third request denied with retry-after');
ok(limit.take('login:2',p,1003).allowed,'client isolation');
ok(!limit.take('login:3',p,1004).allowed,'bounded-memory store fails closed for new clients');
ok(limit.take('login:1',p,2000).allowed,'limit resets precisely at window boundary');
limit.cleanExpired(3000);
ok(limit.size===0,'expired keys reclaimed');
ok(RATE_POLICIES.LOGIN.limit>1 && RATE_POLICIES.REGISTER.windowMs>=60000 && RATE_POLICIES.ENQUIRY.limit>0,'policies have bounded thresholds');
assert.throws(()=>new RequestLimiter(0)); checks++;
assert.throws(()=>limit.take('',p,4000)); checks++;
assert.throws(()=>limit.take('a',{limit:0,windowMs:1000},4000)); checks++;
console.log(`PASS: Milestone 6 security and rate-limit contracts (${checks} assertions)`);
