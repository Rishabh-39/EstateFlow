import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {isPatchedMulterVersion,assertSafeManifest,collectInstalledMulterVersions,summarizeMulterTree} from '../scripts/m10-security-core.mjs';
import {checkRuntimeEnvironment} from '../scripts/verify-runtime-config-m10.mjs';
const pkg=JSON.parse(readFileSync('package.json','utf8'));
let n=0;
function check(ok,label){assert.ok(ok,label);n++;console.log('PASS:',label)}
check(/^0\.(?:1[0-9]|[2-9][0-9])\.\d+$/.test(pkg.version),'Milestone 10+ security checks apply to current release');
check(assertSafeManifest(pkg).length===0,'Multer 2.5.0 override required without upgrading NestJS major');
check(!isPatchedMulterVersion('2.0.0')&&!isPatchedMulterVersion('2.4.0'),'Earlier affected versions rejected');
check(isPatchedMulterVersion('2.5.0')&&isPatchedMulterVersion('2.5.1'),'Patched Multer 2.x accepted');
check(!isPatchedMulterVersion('bad')&&!isPatchedMulterVersion('unknown'),'Unresolved versions fail closed');
check(isPatchedMulterVersion('3.0.0'),'Newer major version is not flagged by this advisory');
const tree={dependencies:{'@nestjs/platform-express':{version:'11.1.0',dependencies:{multer:{version:'2.5.0'}}}}};
check(collectInstalledMulterVersions(tree).length===1,'Nested transitive dependency detected');
check(summarizeMulterTree(tree).errors.length===0,'Patched transitive dependency passes');
const bad={dependencies:{'@nestjs/platform-express':{dependencies:{multer:{version:'2.4.0'}}}}};
check(summarizeMulterTree(bad).errors.length===1,'Vulnerable nested Multer fails');
check(summarizeMulterTree({dependencies:{}}).errors.length===1,'Missing installation fails closed');
const normal={NODE_ENV:'development',JWT_SECRET:'0123456789abcdef'.repeat(4),CORS_ORIGIN:'http://localhost:5173'};
check(checkRuntimeEnvironment(normal).length===0,'Local development CORS accepted');
check(checkRuntimeEnvironment({...normal,JWT_SECRET:'REPLACE_WITH_SECRET'}).length>0,'Placeholder JWT rejected');
check(checkRuntimeEnvironment({...normal,JWT_SECRET:'a'.repeat(64)}).length>0,'Low-entropy repeated JWT secret rejected');
const production={...normal,NODE_ENV:'production',CORS_ORIGIN:'https://estateflow.example',DB_HOST:'db.internal',DB_PASSWORD:'redacted-fake-value',DB_NAME:'estateflow'};
check(checkRuntimeEnvironment(production).length===0,'HTTPS production origin accepted');
check(checkRuntimeEnvironment({...production,CORS_ORIGIN:'*'}).length>0,'Wildcard CORS rejected in production');
check(checkRuntimeEnvironment({...production,CORS_ORIGIN:'http://localhost:5173'}).length>0,'HTTP localhost CORS rejected in production');
check(checkRuntimeEnvironment({...production,CORS_ORIGIN:'https://'}).length>0,'Invalid HTTPS origin rejected');
check(checkRuntimeEnvironment({...production,DB_NAME:'estateflow_test'}).length>0,'Test database rejected for production');
console.log(`ALL ${n} ESTATEFLOW M10 SECURITY ASSERTIONS PASSED`);
