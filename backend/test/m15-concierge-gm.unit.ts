import assert from 'node:assert/strict';
import { extractRequirements, safeDraft } from '../src/agent/classifier';
import { localGuestGuidance, optionalGemini, guestAdvisory } from '../src/agent/generative';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const g=(s:string)=>localGuestGuidance(s);
assert.match(g('Can the lawn hold 200 guests?'),/date|venue/i);
assert.doesNotMatch(g('Can the lawn hold 200 guests?'),/400 guests|confirmed/i);
assert.match(g('Vegetarian catering options'),/dietary|vegetarian/i);
assert.match(g('What does a 2-night stay cost?'),/quote|price|rates/i);
assert.match(g('I am unhappy with a dirty room'),/General Manager/i);
assert.notEqual(g('Vegetarian catering options'),g('Can the lawn hold 200 guests?'));
const e=extractRequirements('Wedding for 200 guests with 35 rooms, 70 cars');
const w=safeDraft('Rishabh','WEDDING',e,'Wedding for 200 guests');
const c=safeDraft('Rishabh','COMPLAINT',e,'The room is dirty');
const u=safeDraft('Rishabh','UNKNOWN',e,'Vegetarian catering options');
assert.match(w,/200 guests/);
assert.match(w,/No reservation has been made yet/);
assert.match(c,/General Manager/);
assert.match(u,/dietary|catering/i);
assert.notEqual(w,c);
assert.notEqual(c,u);
guestAdvisory('Vegetarian catering options').then(r=>{assert.equal(r.mode,'local-guided');}).catch(e=>{console.error(e);process.exitCode=1;});
const front=join(process.cwd(),'../frontend/src');
const alloc=readFileSync(join(front,'routes/staff.allocation.tsx'),'utf8');
assert.match(alloc,/await api\.saveAllocation\(e\.id, counts, notes\); return api\.moveAllocation/);
assert.match(alloc,/submit\.isError/);
const inbox=readFileSync(join(front,'routes/staff.inbox.tsx'),'utf8');
assert.match(inbox,/waLink\(e\.phone\|\|e\.from, draft\)/);
assert.match(inbox,/WhatsApp/);
assert.match(inbox,/Regenerate AI draft/);
const concierge=readFileSync(join(front,'components/estate/ai-concierge.tsx'),'utf8');
assert.match(concierge,/concierge:true/);
assert.match(concierge,/conciergeReply/);
