import assert from 'node:assert/strict';
import { conversationFacts, contextualGuestReply, withConversationFacts } from '../src/enquiries/concierge-memory';
import { extractRequirements } from '../src/agent/classifier';
import { guestAdvisory } from '../src/agent/generative';

process.env.AI_PROVIDER='local-guided';
const one='i want to book resort on 17/11/2026';
const two='guests 20000 and venue i want youto suggest';
const three='can you check availability?';
const facts=conversationFacts([one,two]);
assert.equal(facts.dateIso,'2026-11-17');
assert.equal(facts.dateText,'17/11/2026');
assert.equal(facts.guestCount,20000);
assert.equal(facts.requestedVenue,null);
assert.equal(facts.venueSuggestionRequested,true);
const recommendation=contextualGuestReply(two,facts);
assert.ok(recommendation);
assert.match(recommendation,/17\/11\/2026/);
assert.match(recommendation,/20,000 guests/);
assert.match(recommendation,/suggest a venue/i);
assert.doesNotMatch(recommendation,/please confirm (?:the )?event date|what is your event date/i);
assert.doesNotMatch(recommendation,/venue you need/i);
assert.match(recommendation,/no reservation has been made/i);
const next=conversationFacts([one,two,three]);
assert.equal(next.dateIso,'2026-11-17');
assert.equal(next.guestCount,20000);
const availability=contextualGuestReply(three,next);
assert.ok(availability);
assert.match(availability,/17\/11\/2026/);
assert.match(availability,/20,000 guests/);
assert.match(availability,/not confirmed/i);
assert.doesNotMatch(availability,/please provide your event date/i);
assert.match(availability,/previously asked for a venue recommendation/i);
const rescheduled=conversationFacts([one,two,'Please change the date to 20/11/2026']);
assert.equal(rescheduled.dateIso,'2026-11-20');
assert.equal(rescheduled.guestCount,20000);
const rescheduledAgain=conversationFacts([one,two,'change the date to 20 November']);
assert.equal(rescheduledAgain.dateIso,'2026-11-20');
const correctedFromTo=conversationFacts([one,two,'Change the date from 17/11/2026 to 20/11/2026']);
assert.equal(correctedFromTo.dateIso,'2026-11-20');
assert.equal(correctedFromTo.exactCheckOut,null,'Changing a date is not a stay date range');
const noOverwrite=conversationFacts([one,two,'I want to change the date','31/02/2027']);
assert.equal(noOverwrite.dateIso,'2026-11-17');
assert.equal(noOverwrite.guestCount,20000);
const askNewDate=contextualGuestReply('I want to change the date',noOverwrite);
assert.ok(askNewDate);
assert.match(askNewDate,/what new exact date/i);
assert.match(askNewDate,/17\/11\/2026/);
assert.equal(conversationFacts(['20/11/2026']).guestCount,null,'No inherited facts from another conversation');
const pendingUpdate=withConversationFacts(extractRequirements(two),facts);
assert.equal(pendingUpdate.dateText,'17/11/2026','Staff inbox must retain first confirmed date');
assert.equal(pendingUpdate.guestCount,20000);
const lawn=conversationFacts([one,two,'For the wedding lawn, check availability']);
assert.equal(lawn.requestedVenue,'LAWN');
assert.equal(lawn.venueSuggestionRequested,false);
assert.match(contextualGuestReply('For the wedding lawn, check availability',lawn,'BOOKED')!,/already claimed/i);
assert.match(contextualGuestReply('For the wedding lawn, check availability',lawn,'OPEN_SLOT')!,/does not prove/i);
assert.match(contextualGuestReply('For the wedding lawn, check availability',lawn,'NOT_CONFIGURED')!,/not been configured/i);
(async()=>{
 const ai=await guestAdvisory(two,one,facts);
 assert.equal(ai.mode,'local-guided');
 assert.match(ai.text,/17\/11\/2026/);
 assert.match(ai.text,/20,000 guests/);
 console.log('M31 conversation memory + venue guidance regression tests passed');
})().catch(err=>{console.error(err);process.exitCode=1;});
