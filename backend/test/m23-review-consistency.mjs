/** Focused regression: pure validation + source guardrails. No live DB claims. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { createRequire } from 'node:module';
const require=createRequire(import.meta.url);
const ts=require('typescript');
const source=fs.readFileSync('../frontend/src/lib/estate/event-review.ts','utf8');
const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const mod={exports:{}};vm.runInNewContext(code,{module:mod,exports:mod.exports});
const {reviewMissing,isDayEvent,canSubmitReview}=mod.exports;
let checks=0;const check=(ok,msg)=>{assert.ok(ok,msg);checks++};
const day={eventType:'Celebration',venuePreference:'LAWN',startDate:'2026-11-23',nights:0,guests:100,rooms:0,needsLawn:true,diningCovers:0,parking:0,eventStaff:10};
check(isDayEvent(day),'day-only event recognized');
check(canSubmitReview(day),'day-only celebration allowed without accommodation');
check(!reviewMissing(day).length,'explicit zero service quantities are not interpreted as missing');
check(!canSubmitReview({...day,rooms:10}),'rooms require positive stay nights');
check(!canSubmitReview({...day,nights:2}),'roomless events require zero nights');
check(!canSubmitReview({...day,parking:null}),'unknown parking requires staff confirmation');
check(!canSubmitReview({...day,diningCovers:null}),'unknown catering requires staff confirmation');
check(!canSubmitReview({...day,venuePreference:'UNCONFIRMED'}),'venue is required');
check(!canSubmitReview({...day,startDate:'2026-02-30'}),'invalid calendar date rejected');
check(canSubmitReview({...day,eventType:'Corporate offsite'}),'offsite can use lawn subject to inventory');
check(canSubmitReview({...day,eventType:'Wedding'}),'wedding can be day-only when no rooms requested');
const ui=fs.readFileSync('../frontend/src/routes/staff.workbench.$enquiryId.tsx','utf8');
const live=fs.readFileSync('../frontend/src/services/api/live.ts','utf8');
const events=fs.readFileSync('src/events/events.ts','utf8');
const enquiries=fs.readFileSync('src/enquiries/enquiries.ts','utf8');
const approval=fs.readFileSync('src/events/approval.ts','utf8');
check(ui.includes('Submit feasible proposal to GM'),'staff button does not falsely grant GM approval');
check(ui.includes('review.data?.status===\'GM_APPROVED\''),'client confirmation only appears after GM approval');
check(ui.includes('Separate complaint escalation')||ui.includes('Separate complaint escalation'.toLowerCase())||ui.includes('aria-label="Separate complaint escalation"'),'complaint action separate from event approval');
check(ui.includes('window.prompt(')&&ui.includes('escalateComplaint.mutate(reason.trim())'),'complaint escalation captures reason');
check(ui.includes('No overnight accommodation')&&ui.includes('No catering required'),'conditional zero actions visible');
check(ui.includes('items-start')&&ui.includes('reviewMissing(r)'),'balanced resource card and transparent missing fields');
check(live.includes('Math.max(1,r.nights!)'),'day-only events use valid event day range without booking room nights');
check(live.includes('reviewMissing(r)'),'API payload enforces same review validation as UI');
check(live.includes('nights:r.nights'),'zero nights persisted as explicit staff correction');
check(enquiries.includes("'APPROVAL_PENDING','APPROVED','CLIENT_CONFIRMED'"),'pending GM enquiries cannot be edited by staff');
check(events.includes("ar.status IN ('PENDING_GM','GM_APPROVED','CLIENT_CONFIRMED')"),'pending GM event proposal cannot change via PUT endpoint');
check(events.includes('exclusive_venue_claims')&&events.includes('reserveInsideApproval'),'exclusive venue claim remains enforced in DB');
check(approval.includes("user.role!=='GM'")&&approval.includes("user.role!=='STAFF'"),'separate GM and staff authorities remain enforced');
check(approval.includes('confirmedSent!==true'),'client confirmation requires staff attestation');
for(const file of ['../frontend/src/routes/staff.workbench.$enquiryId.tsx','../frontend/src/services/api/live.ts','../frontend/src/lib/estate/event-review.ts','src/events/events.ts','src/enquiries/enquiries.ts']){
 const input=fs.readFileSync(file,'utf8');const out=ts.transpileModule(input,{fileName:file,reportDiagnostics:true,compilerOptions:{jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}});
 const errors=(out.diagnostics||[]).filter(d=>d.category===ts.DiagnosticCategory.Error);
 check(errors.length===0,`TypeScript parse: ${file} ${errors.map(e=>ts.flattenDiagnosticMessageText(e.messageText,' ')).join(';')}`);
}
console.log(`PASS M23 REVIEW CONSISTENCY (${checks} assertions; no live PostgreSQL/browser execution)`);
